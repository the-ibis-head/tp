import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { test } from 'node:test';

import { handleDefaults } from '../src/commands/defaults.js';

function withEnv(value, fn) {
  const original = process.env.DROPBOX_PATH;
  if (value === null) delete process.env.DROPBOX_PATH;
  else process.env.DROPBOX_PATH = value;
  try {
    return fn();
  } finally {
    if (original === undefined) delete process.env.DROPBOX_PATH;
    else process.env.DROPBOX_PATH = original;
  }
}

function capture(fn) {
  const logs = [];
  const errors = [];
  const originalLog = console.log;
  const originalError = console.error;
  console.log = (...parts) => logs.push(parts.join(' '));
  console.error = (...parts) => errors.push(parts.join(' '));
  try {
    return { result: fn(), output: logs.join('\n'), errors: errors.join('\n') };
  } finally {
    console.log = originalLog;
    console.error = originalError;
  }
}

test('generate reports an error when DROPBOX_PATH is unset', () => {
  const { result, errors } = withEnv(null, () => capture(() => handleDefaults({ subcommand: 'generate' })));
  assert.equal(result, 1);
  assert.match(errors, /DROPBOX_PATH environment variable is not set/);
});

test('generate writes into DROPBOX_PATH/Projects/dotfiles/macos', () => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'tp-defaults-'));
  try {
    const { result } = withEnv(dir, () => capture(() => handleDefaults({ subcommand: 'generate' })));
    assert.equal(result, 0);
    const target = path.join(dir, 'Projects', 'dotfiles', 'macos', 'defaults.txt');
    assert.ok(fs.existsSync(target), `expected ${target}`);
    assert.match(fs.readFileSync(target, 'utf8'), /^# Generated by tp - defaults\.txt/);
    assert.match(fs.readFileSync(target, 'utf8'), /^defaults write /m);
  } finally {
    fs.rmSync(dir, { recursive: true, force: true });
  }
});
