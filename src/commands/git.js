import fs from 'node:fs';
import path from 'node:path';
import {
  command, _GIT_SUBCOMMAND_ARG, _FILTER_FLAG, filterTerms, getField,
  loadData, matchFilter, recordType, singleSubcommand,
  configuredDropboxPath, displayError, displayInfo, displaySection, displayWarn,
  bold, dim, green, printTable,
} from '../core/index.js';

function timestamp() {
  const d = new Date();
  const pad = (n) => String(n).padStart(2, '0');
  return `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())} ` +
    `${pad(d.getHours())}:${pad(d.getMinutes())}:${pad(d.getSeconds())}`;
}

function loadGitData(records) {
  const configs = [];
  const ignores = [];
  for (const record of records) {
    const rtype = recordType(record).trim().toLowerCase();
    const fields = record.fields;
    if (rtype === 'git_config') {
      if (!Array.isArray(fields) || fields.length < 2) continue;
      const key = getField(fields, 0);
      const value = getField(fields, 1);
      if (!key) continue;
      configs.push({ key, value });
    } else if (rtype === 'git_ignore') {
      if (!Array.isArray(fields) || fields.length < 1) continue;
      const pattern = getField(fields, 0);
      if (!pattern) continue;
      ignores.push({ pattern });
    }
  }
  return { configs, ignores };
}

function writeLines(outputPath, lines) {
  fs.mkdirSync(path.dirname(outputPath), { recursive: true });
  fs.writeFileSync(outputPath, `${lines.join('\n')}\n`, 'utf8');
}

function displayLines(lines) {
  console.log();
  for (const line of lines) console.log(`  ${dim(line)}`);
  console.log();
}

export function handleGit(args) {
  const subcommand = singleSubcommand(args, 'list');
  const { configs, ignores } = loadGitData(loadData());
  if (subcommand === 'generate') {
    const dropbox = configuredDropboxPath();
    if (!dropbox) {
      displayError('DROPBOX_PATH environment variable is not set. '
        + 'Set it to your Dropbox directory to generate git config.');
      return 1;
    }
    displaySection('Generate git config');
    if (!configs.length) {
      displayWarn('No git_config records found in data file');
      return 1;
    }
    const configPath = path.join(dropbox, 'Projects', 'dotfiles', 'git', 'config');
    const lines = [
      '# config — generated by tp',
      `# ${timestamp()}`,
      '',
    ];
    let currentSection = null;
    for (const c of configs) {
      const dot = c.key.indexOf('.');
      const section = dot < 0 ? c.key : c.key.slice(0, dot);
      const setting = dot < 0 ? '' : c.key.slice(dot + 1);
      if (section !== currentSection) {
        lines.push(`[${section}]`);
        currentSection = section;
      }
      lines.push(`\t${setting} = ${c.value}`);
    }
    writeLines(configPath, lines);
    displayInfo(`config written to ${green(String(configPath))}`);
    displayLines(lines);
    if (ignores.length) {
      displaySection('Generate git ignore');
      const ignorePath = path.join(dropbox, 'Projects', 'dotfiles', 'git', 'ignore');
      const ignoreLines = [
        '# ignore — generated by tp git generate',
        `# ${timestamp()}`,
        '',
      ];
      for (const i of ignores) ignoreLines.push(i.pattern);
      writeLines(ignorePath, ignoreLines);
      displayInfo(`ignore written to ${green(String(ignorePath))}`);
      displayLines(ignoreLines);
    }
    return 0;
  }
  if (subcommand === 'ignore') {
    displaySection('List git ignore patterns');
    if (!ignores.length) {
      displayWarn('No git_ignore records found in data file');
      return 1;
    }
    const terms = filterTerms(args);
    const filtered = ignores.filter((i) => matchFilter(terms, [i.pattern]));
    const rows = filtered.map((i) => [green(i.pattern)]);
    printTable(['Pattern'], rows);
    console.log();
    displayInfo(`${green(String(filtered.length))} ignore pattern(s) listed`);
    return 0;
  }
  displaySection('List git configuration');
  if (!configs.length) {
    displayWarn('No git configuration found');
    return 1;
  }
  const terms = filterTerms(args);
  const filtered = configs.filter((c) => matchFilter(terms, [c.key, c.value]));
  const rows = filtered.map((c) => [bold(c.key), green(c.value)]);
  printTable(['Key', 'Value'], rows);
  console.log();
  displayInfo(`${green(String(filtered.length))} config entry(s) listed`);
  return 0;
}

export const COMMAND = command({
  name: 'git',
  desc: 'Manage git configuration',
  handler: handleGit,
  flags: [_GIT_SUBCOMMAND_ARG, _FILTER_FLAG],
  visibility: 'public',
});
