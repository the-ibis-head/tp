import fs from 'node:fs';
import path from 'node:path';
import {
  command, _ZSH_SUBCOMMAND_ARG, _FILTER_FLAG, filterTerms, getField,
  loadData, matchFilter, recordType, singleSubcommand,
  configuredDropboxPath, displayError, displayInfo, displaySection, displayWarn,
  bold, dim, green, printTable,
} from '../core/index.js';

function timestamp() {
  const d = new Date();
  const pad = (n) => String(n).padStart(2, '0');
  return `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())} ` +
    `${pad(d.getHours())}:${pad(d.getMinutes())}:${pad(d.getSeconds())}`;
}

function loadZshData(records, terms) {
  const options = [];
  const exports = [];
  const paths = [];
  const aliases = [];
  const plugins = [];
  for (const record of records) {
    const rtype = recordType(record).trim().toLowerCase();
    const fields = Array.isArray(record.fields) ? record.fields : [];
    if (rtype === 'zsh_option') {
      const name = getField(fields, 0);
      const description = getField(fields, 1);
      if (!name || !matchFilter(terms, [name, description])) continue;
      options.push({ name, description });
    } else if (rtype === 'zsh_export') {
      const key = getField(fields, 0);
      const value = getField(fields, 1);
      if (!key || !matchFilter(terms, [key, value])) continue;
      exports.push({ key, value });
    } else if (rtype === 'zsh_path') {
      const p = getField(fields, 0);
      if (!p || !matchFilter(terms, [p])) continue;
      paths.push({ path: p });
    } else if (rtype === 'zsh_alias') {
      const alias = getField(fields, 0);
      const cmd = getField(fields, 1);
      if (!alias || !matchFilter(terms, [alias, cmd])) continue;
      aliases.push({ alias, command: cmd });
    } else if (rtype === 'zsh_plugin') {
      const name = getField(fields, 0);
      const url = getField(fields, 1);
      if (!name || !matchFilter(terms, [name, url])) continue;
      plugins.push({ name, url });
    }
  }
  return { options, exports, paths, aliases, plugins };
}

export function handleZsh(args) {
  const subcommand = singleSubcommand(args, 'options');
  const terms = filterTerms(args);
  const { options, exports, paths, aliases, plugins } = loadZshData(loadData(), terms);
  if (subcommand === 'generate') {
    const dropbox = configuredDropboxPath();
    if (!dropbox) {
      displayError('DROPBOX_PATH environment variable is not set. '
        + 'Set it to your Dropbox directory to generate zsh config.');
      return 1;
    }
    displaySection('Generate zsh config');
    const configPath = path.join(dropbox, 'Projects', 'dotfiles', 'zsh', 'config');
    fs.mkdirSync(path.dirname(configPath), { recursive: true });
    const lines = [
      '# config — generated by tp',
      `# ${timestamp()}`,
      '',
    ];
    if (options.length) {
      lines.push('# Options');
      for (const o of options) lines.push(`setopt ${o.name}`);
      lines.push('');
    }
    if (exports.length) {
      lines.push('# Exports');
      for (const e of exports) lines.push(`export ${e.key}="${e.value}"`);
      lines.push('');
    }
    if (paths.length) {
      lines.push('# Path');
      for (const p of paths) lines.push(`export PATH="${p.path}:$PATH"`);
      lines.push('');
    }
    if (aliases.length) {
      lines.push('# Aliases');
      for (const a of aliases) lines.push(`alias ${a.alias}='${a.command}'`);
      lines.push('');
    }
    lines.push('# Pyenv');
    lines.push('export PYENV_ROOT="$HOME/.pyenv"');
    lines.push('[[ -d $PYENV_ROOT/bin ]] && export PATH="$PYENV_ROOT/bin:$PATH"');
    lines.push('eval "$(pyenv init - zsh)"');
    lines.push('');
    lines.push('# Nvm');
    lines.push('export NVM_DIR="$HOME/.nvm"');
    lines.push('[ -s "$NVM_DIR/nvm.sh" ] && \\. "$NVM_DIR/nvm.sh"');
    lines.push('[ -s "$NVM_DIR/bash_completion" ] && \\. "$NVM_DIR/bash_completion"');
    lines.push('');
    lines.push('# Zsh');
    lines.push('export ZSH="$HOME/.oh-my-zsh"');
    if (plugins.length) {
      lines.push(`plugins=(${plugins.map((p) => p.name).join(' ')})`);
    }
    lines.push('source $ZSH/oh-my-zsh.sh');
    lines.push('source $(brew --prefix)/share/zsh-autosuggestions/zsh-autosuggestions.zsh');
    lines.push('source $(brew --prefix)/share/zsh-syntax-highlighting/zsh-syntax-highlighting.zsh');
    lines.push('eval "$(starship init zsh)"');
    fs.writeFileSync(configPath, `${lines.join('\n')}\n`, 'utf8');
    displayInfo(`config written to ${green(String(configPath))}`);
    console.log();
    for (const line of lines) console.log(`  ${dim(line)}`);
    console.log();
    return 0;
  }
  if (subcommand === 'exports') {
    displaySection('List zsh exports');
    if (!exports.length) {
      displayWarn('No zsh_export records found in data file');
      return 1;
    }
    const rows = exports.map((e) => [bold(e.key), green(e.value)]);
    printTable(['Key', 'Value'], rows);
    console.log();
    displayInfo(`${green(String(exports.length))} export(s) listed`);
    return 0;
  }
  if (subcommand === 'paths') {
    displaySection('List zsh paths');
    if (!paths.length) {
      displayWarn('No zsh_path records found in data file');
      return 1;
    }
    for (const p of paths) console.log(`  ${green(p.path)}`);
    console.log();
    displayInfo(`${green(String(paths.length))} path(s) listed`);
    return 0;
  }
  if (subcommand === 'aliases') {
    displaySection('List zsh aliases');
    if (!aliases.length) {
      displayWarn('No zsh_alias records found in data file');
      return 1;
    }
    const rows = aliases.map((a) => [bold(a.alias), green(a.command)]);
    printTable(['Alias', 'Command'], rows);
    console.log();
    displayInfo(`${green(String(aliases.length))} alias(es) listed`);
    return 0;
  }
  if (subcommand === 'plugins') {
    displaySection('List zsh plugins');
    if (!plugins.length) {
      displayWarn('No zsh_plugin records found in data file');
      return 1;
    }
    const rows = plugins.map((p) => [bold(p.name), dim(p.url)]);
    printTable(['Plugin', 'URL'], rows);
    console.log();
    displayInfo(`${green(String(plugins.length))} plugin(s) listed`);
    return 0;
  }
  displaySection('List zsh options');
  if (!options.length) {
    displayWarn('No zsh_option records found in data file');
    return 1;
  }
  const rows = options.map((o) => [bold(o.name)]);
  printTable(['Option'], rows);
  console.log();
  displayInfo(`${green(String(options.length))} option(s) listed`);
  return 0;
}

export const COMMAND = command({
  name: 'zsh',
  desc: 'Manage zsh configuration',
  handler: handleZsh,
  flags: [_ZSH_SUBCOMMAND_ARG, _FILTER_FLAG],
  visibility: 'public',
});
