import fs from 'node:fs';
import path from 'node:path';
import {
  command, _VSCODE_SUBCOMMAND_ARG, _FILTER_FLAG, filterTerms, getField,
  loadData, matchFilter, recordType, singleSubcommand,
  configuredDropboxPath, displayError, displayInfo, displaySection, displayWarn,
  bold, dim, green, printTable,
} from '../core/index.js';

function timestamp() {
  const d = new Date();
  const pad = (n) => String(n).padStart(2, '0');
  return `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())} ` +
    `${pad(d.getHours())}:${pad(d.getMinutes())}:${pad(d.getSeconds())}`;
}

function coerceJsonValue(value) {
  const text = String(value ?? '').trim();
  if (text === 'true') return true;
  if (text === 'false') return false;
  if (text === 'null') return null;
  if (/^-?\d+(?:\.\d+)?$/.test(text)) return Number(text);
  try {
    return JSON.parse(text);
  } catch {
    return String(value ?? '');
  }
}

function loadVscodeData(records) {
  const settings = [];
  const keybindings = [];
  const extensions = [];
  for (const record of records) {
    const rtype = recordType(record).trim().toLowerCase();
    const fields = record.fields;
    if (rtype === 'vscode_setting') {
      if (!Array.isArray(fields) || fields.length < 2) continue;
      const key = getField(fields, 0);
      const value = getField(fields, 1);
      if (!key) continue;
      settings.push({ key, value });
    } else if (rtype === 'vscode_keybinding') {
      if (!Array.isArray(fields) || fields.length < 2) continue;
      const key = getField(fields, 0);
      const cmd = getField(fields, 1);
      if (!key || !cmd) continue;
      keybindings.push({ key, command: cmd });
    } else if (rtype === 'vscode_extension') {
      if (!Array.isArray(fields) || fields.length < 2) continue;
      const name = getField(fields, 0);
      const extensionId = getField(fields, 1);
      const url = fields.length > 2 ? getField(fields, 2) : '';
      if (!extensionId) continue;
      extensions.push({ name, extensionId, url });
    }
  }
  return { settings, keybindings, extensions };
}

function writeText(filePath, text) {
  fs.writeFileSync(filePath, `${text}\n`, 'utf8');
}

function displayText(text) {
  console.log();
  for (const line of String(text).split(/\r?\n/)) console.log(`  ${dim(line)}`);
  console.log();
}

export function handleVscode(args) {
  const subcommand = singleSubcommand(args, 'list');
  const { settings, keybindings, extensions } = loadVscodeData(loadData());
  if (subcommand === 'generate') {
    const dropbox = configuredDropboxPath();
    if (!dropbox) {
      displayError('DROPBOX_PATH environment variable is not set. '
        + 'Set it to your Dropbox directory to generate vscode configuration.');
      return 1;
    }
    const outputDir = path.join(dropbox, 'Projects', 'dotfiles', 'vscode');
    fs.mkdirSync(outputDir, { recursive: true });
    const generated = [];
    if (settings.length) {
      displaySection('Generate settings.json');
      const settingsPath = path.join(outputDir, 'settings.json');
      const payload = {};
      for (const s of settings) payload[s.key] = coerceJsonValue(s.value);
      const settingsJson = JSON.stringify(payload, null, 4);
      writeText(settingsPath, settingsJson);
      displayInfo(`settings.json written to ${green(String(settingsPath))}`);
      displayText(settingsJson);
      generated.push('settings.json');
    }
    if (keybindings.length) {
      displaySection('Generate keybindings.json');
      const keybindingsPath = path.join(outputDir, 'keybindings.json');
      const kbList = keybindings.map((kb) => ({ key: kb.key, command: kb.command }));
      const keybindingsJson = JSON.stringify(kbList, null, 4);
      writeText(keybindingsPath, keybindingsJson);
      displayInfo(`keybindings.json written to ${green(String(keybindingsPath))}`);
      displayText(keybindingsJson);
      generated.push('keybindings.json');
    }
    if (extensions.length) {
      displaySection('Generate extensions.txt');
      const extensionsPath = path.join(outputDir, 'extensions.txt');
      const extLines = [
        '# extensions.txt — generated by tp',
        `# ${timestamp()}`,
        '',
      ];
      for (const e of extensions) extLines.push(e.extensionId);
      const text = extLines.join('\n');
      writeText(extensionsPath, text);
      displayInfo(`extensions.txt written to ${green(String(extensionsPath))}`);
      displayText(text);
      generated.push('extensions.txt');
    }
    if (!generated.length) {
      displayWarn('No vscode records found in data file');
      return 1;
    }
    displayInfo(`${green(String(generated.length))} file(s) generated`);
    return 0;
  }
  if (subcommand === 'keybindings') {
    if (!keybindings.length) {
      displayWarn('No vscode_keybinding records found in data file');
      return 1;
    }
    const terms = filterTerms(args);
    const filtered = keybindings.filter((kb) => matchFilter(terms, [kb.key, kb.command]));
    displaySection('List vscode keybindings');
    const rows = filtered.map((kb) => [bold(kb.key), green(kb.command)]);
    printTable(['Key', 'Command'], rows);
    console.log();
    displayInfo(`${green(String(filtered.length))} keybinding(s) listed`);
    return 0;
  }
  if (subcommand === 'extensions') {
    if (!extensions.length) {
      displayWarn('No vscode_extension records found in data file');
      return 1;
    }
    const terms = filterTerms(args);
    const filtered = extensions.filter((e) => matchFilter(terms, [e.name, e.extensionId, e.url]));
    displaySection('List vscode extensions');
    const rows = filtered.map((e) => [bold(e.name), green(e.extensionId), dim(e.url)]);
    printTable(['Name', 'Extension ID', 'URL'], rows);
    console.log();
    displayInfo(`${green(String(filtered.length))} extension(s) listed`);
    return 0;
  }
  if (!settings.length) {
    displayWarn('No vscode setting found');
    return 1;
  }
  const terms = filterTerms(args);
  const filtered = settings.filter((s) => matchFilter(terms, [s.key, s.value]));
  displaySection('List vscode settings');
  const rows = filtered.map((s) => [bold(s.key), green(s.value)]);
  printTable(['Key', 'Value'], rows);
  console.log();
  displayInfo(`${green(String(filtered.length))} setting(s) listed`);
  return 0;
}

export const COMMAND = command({
  name: 'vscode',
  desc: 'Manage vscode configuration',
  handler: handleVscode,
  flags: [_VSCODE_SUBCOMMAND_ARG, _FILTER_FLAG],
  visibility: 'public',
});
