import fs from 'node:fs';
import path from 'node:path';
import {
  command, _DUTI_SUBCOMMAND_ARG, _FILTER_FLAG, filterTerms, getField,
  loadData, matchFilter, recordType, singleSubcommand,
  configuredDropboxPath, displayError, displayInfo, displaySection, displayWarn,
  bold, dim, green, printTable,
} from '../core/index.js';

function timestamp() {
  const d = new Date();
  const pad = (n) => String(n).padStart(2, '0');
  return `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())} ` +
    `${pad(d.getHours())}:${pad(d.getMinutes())}:${pad(d.getSeconds())}`;
}

function loadFormats(records) {
  const formats = [];
  for (const record of records) {
    if (recordType(record).trim().toLowerCase() !== 'duti_file_format') continue;
    const fields = record.fields;
    if (!Array.isArray(fields) || fields.length < 3) continue;
    const bundleId = getField(fields, 0);
    const extension = getField(fields, 1);
    const role = getField(fields, 2);
    if (!bundleId || !extension) continue;
    formats.push({ bundleId, extension, role });
  }
  return formats;
}

export function handleDuti(args) {
  const subcommand = singleSubcommand(args, 'list');
  const formats = loadFormats(loadData());
  if (subcommand === 'generate') {
    const dropbox = configuredDropboxPath();
    if (!dropbox) {
      displayError('DROPBOX_PATH environment variable is not set. '
        + 'Set it to your Dropbox directory to generate formats.txt.');
      return 1;
    }
    displaySection('Generate formats.txt');
    const outputPath = path.join(dropbox, 'Projects', 'dotfiles', 'duti', 'formats.txt');
    fs.mkdirSync(path.dirname(outputPath), { recursive: true });
    const lines = [
      '# formats.txt — generated by tp',
      `# ${timestamp()}`,
      '',
    ];
    for (const f of formats) lines.push(`${f.bundleId} ${f.extension} ${f.role}`);
    fs.writeFileSync(outputPath, `${lines.join('\n')}\n`, 'utf8');
    displayInfo(`formats.txt written to ${green(String(outputPath))}`);
    console.log();
    for (const line of lines) console.log(`  ${dim(line)}`);
    console.log();
    return 0;
  }
  displaySection('List duti file formats');
  if (!formats.length) {
    console.log();
    displayWarn('No duti file formats found');
    return 1;
  }
  const terms = filterTerms(args);
  const filtered = formats.filter((f) => matchFilter(terms, [f.bundleId, f.extension, f.role]));
  const rows = filtered.map((f) => [bold(f.bundleId), green(f.extension), dim(f.role)]);
  printTable(['Bundle ID', 'Extension', 'Role'], rows);
  console.log();
  displayInfo(`${green(String(filtered.length))} format(s) listed`);
  return 0;
}

export const COMMAND = command({
  name: 'duti',
  desc: 'Manage duti file associations',
  handler: handleDuti,
  flags: [_DUTI_SUBCOMMAND_ARG, _FILTER_FLAG],
  visibility: 'public',
});
